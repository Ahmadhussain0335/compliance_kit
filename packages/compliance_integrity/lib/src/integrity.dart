import 'dart:async';

import 'package:compliance_core/compliance_core.dart';

import 'integrity_platform.dart';
import 'integrity_result.dart';
import 'pigeon_integrity_platform.dart';

/// App and device integrity checks with Google Play Integrity on Android and
/// Apple App Attest on iOS, without Firebase.
///
/// A token on its own proves nothing: send it to your server and verify it
/// there (see the reference server in this repository). The request hash
/// must come from your server, so a token cannot be replayed for a
/// different request.
///
/// No method throws. Failures are returned as [IntegrityFailure] subtypes.
final class Integrity {
  /// Creates an integrity client.
  ///
  /// [cloudProjectNumber] is the Google Cloud project number linked to the
  /// app in the Play Console (Android only).
  Integrity({
    this.cloudProjectNumber,
    this.auditTrail,
    IntegrityPlatform? platform,
    DateTime Function()? clock,
  }) : _platform = platform ?? PigeonIntegrityPlatform(),
       _clock = clock ?? DateTime.now;

  /// Maximum length of a request hash. Play Integrity standard requests
  /// accept at most 500 characters.
  static const int maxRequestHashLength = 500;

  /// Audit event type for a request that produced a token.
  static const String checkPassedEvent = 'integrity_check_passed';

  /// Audit event type for a request that did not produce a token.
  static const String checkFailedEvent = 'integrity_check_failed';

  /// Audit source used by this package.
  static const String auditSource = 'compliance_integrity';

  /// Google Cloud project number (Android).
  final int? cloudProjectNumber;

  /// Optional audit trail. Events contain the result type and token kind
  /// only, never the token.
  final AuditTrail? auditTrail;

  final IntegrityPlatform _platform;
  final DateTime Function() _clock;

  /// Whether this device can produce integrity tokens. Returns `false`
  /// instead of throwing if the check fails.
  Future<bool> isSupported() async {
    try {
      return await _platform.isSupported();
    } on Object {
      return false;
    }
  }

  /// Warms up the platform so the first [requestToken] is faster.
  ///
  /// Returns `null` when ready, or the failure.
  Future<IntegrityFailure?> prepare() async {
    try {
      await _platform.prepare(cloudProjectNumber: cloudProjectNumber);
      return null;
    } on Object catch (e) {
      return mapError(e);
    }
  }

  /// Requests a token bound to [requestHash].
  ///
  /// [requestHash] must be generated by your server for this specific
  /// request (for example a base64url SHA-256 of a server nonce plus the
  /// action), at most [maxRequestHashLength] characters. On iOS the plugin
  /// uses `SHA-256(UTF-8(requestHash))` as App Attest `clientDataHash`.
  ///
  /// On iOS the first successful call returns an
  /// [IntegrityTokenKind.appAttestAttestation]; later calls return
  /// assertions. If your server rejected or lost the attestation, call
  /// [reset] and request again.
  Future<IntegrityResult> requestToken(String requestHash) async {
    final IntegrityResult result;
    if (requestHash.isEmpty || requestHash.length > maxRequestHashLength) {
      result = const IntegrityConfigurationError(
        message: 'requestHash must be 1-$maxRequestHashLength characters.',
      );
    } else {
      result = await _request(requestHash);
    }
    await _audit(result);
    return result;
  }

  /// Discards the stored App Attest key or token provider. The next
  /// [requestToken] on iOS creates and attests a new key.
  Future<void> reset() async {
    try {
      await _platform.reset();
    } on Object {
      // Nothing to reset is not an error for the caller.
    }
  }

  Future<IntegrityResult> _request(String requestHash) async {
    try {
      final token = await _platform.requestToken(
        requestHash: requestHash,
        cloudProjectNumber: cloudProjectNumber,
      );
      return IntegritySuccess(
        token: token.token,
        kind: token.kind,
        keyId: token.keyId,
      );
    } on Object catch (e) {
      return mapError(e);
    }
  }

  /// Maps an error from the platform layer to an [IntegrityFailure].
  static IntegrityFailure mapError(Object error) {
    if (error is! IntegrityPlatformException) {
      return const IntegrityPlatformError(
        message: 'Unexpected error from the platform layer.',
      );
    }
    final message = error.message;
    final code = error.platformCode;
    return switch (error.code) {
      IntegrityErrorCodes.unsupported => IntegrityUnsupported(
        message: message,
        platformCode: code,
      ),
      IntegrityErrorCodes.playServicesMissing => IntegrityPlayServicesMissing(
        message: message,
        platformCode: code,
      ),
      IntegrityErrorCodes.network => IntegrityNetworkError(
        message: message,
        platformCode: code,
      ),
      IntegrityErrorCodes.rateLimited => IntegrityRateLimited(
        message: message,
        platformCode: code,
      ),
      IntegrityErrorCodes.configuration => IntegrityConfigurationError(
        message: message,
        platformCode: code,
      ),
      IntegrityErrorCodes.transient => IntegrityPlatformError(
        message: message,
        platformCode: code,
        retryable: true,
      ),
      _ => IntegrityPlatformError(message: message, platformCode: code),
    };
  }

  Future<void> _audit(IntegrityResult result) async {
    final trail = auditTrail;
    if (trail == null) return;
    try {
      await trail.record(
        AuditEvent(
          type: result.isSuccess ? checkPassedEvent : checkFailedEvent,
          source: auditSource,
          timestamp: _clock(),
          metadata: {
            'result': result.resultType,
            if (result case IntegritySuccess(:final kind)) 'kind': kind.name,
            if (result case IntegrityFailure(:final platformCode?))
              'platform_code': platformCode.length > 64
                  ? platformCode.substring(0, 64)
                  : platformCode,
          },
        ),
      );
    } on Object {
      // A failing audit trail must not affect the integrity check.
    }
  }
}
